export function isApprovedMissionUrl(candidate) {
  if (typeof candidate !== "string" || candidate.length === 0) {
    return false;
  }

  try {
    const url = new URL(candidate);
    return (
      APPROVED_MISSION_ORIGINS.includes(url.origin) &&
      url.pathname === "/" &&
      url.search === "" &&
      url.hash === "" &&
      url.username === "" &&
      url.password === ""
    );
  } catch {
    return false;
  }
}

